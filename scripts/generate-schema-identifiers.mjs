import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const metadataPath=new URL('../contracts/schema-identifiers.json',import.meta.url);
const tsPath=new URL('../src/generated/schema-identifiers.ts',import.meta.url);
const goPath=new URL('../executor/schema_identifiers_generated.go',import.meta.url);
const agentPath=new URL('../src/agent-schema-identifiers.generated.mjs',import.meta.url);
const metadata=JSON.parse(readFileSync(metadataPath,'utf8'));

const dash=({name,version})=>`${name}-v${version}`;
const slash=({name,version})=>`${name}/v${version}`;

const groups={
  AUTHORITY_SCHEMAS:Object.fromEntries(Object.entries(metadata.authority).map(([key,value])=>[key,dash(value)])),
  COMPUTATION_SCHEMAS:Object.fromEntries(Object.entries(metadata.computation).map(([key,value])=>[key,dash(value)])),
  COMPUTATION_RUNNER_SCHEMAS:Object.fromEntries(Object.entries(metadata.computationRunner).map(([key,value])=>[key,dash(value)])),
  OBSERVATION_SCHEMAS:Object.fromEntries(Object.entries(metadata.observation).map(([key,value])=>[key,dash(value)])),
  AGENT_SCHEMAS:Object.fromEntries(Object.entries(metadata.agent).map(([key,value])=>[key,slash(value)])),
  SELF_APPLICATION_SCHEMAS:Object.fromEntries(Object.entries(metadata.selfApplication).map(([key,value])=>[key,dash(value)])),
  GITHUB_AUTHORITY_SCHEMAS:Object.fromEntries(Object.entries(metadata.githubAuthority).map(([key,value])=>[key,slash(value)])),
  PRODUCTION_SCHEMAS:Object.fromEntries(Object.entries(metadata.production).map(([key,value])=>[key,dash(value)])),
  REALIZATION_SCHEMAS:Object.fromEntries(Object.entries(metadata.realization).map(([key,value])=>[key,dash(value)])),
  STORAGE_SCHEMAS:Object.fromEntries(Object.entries(metadata.storage).map(([key,value])=>[key,dash(value)])),
  POSTCONDITION_VERIFIERS:Object.fromEntries(Object.entries(metadata.verifier).map(([key,value])=>[key,slash(value)])),
  ACCEPTANCE_PREDICATES:Object.fromEntries(Object.entries(metadata.acceptancePredicate).map(([key,value])=>[key,slash(value)])),
  ABSENCE_EVIDENCE_KINDS:Object.fromEntries(Object.entries(metadata.evidenceKind).map(([key,value])=>[key,slash(value)])),
  EFFECT_CONTRACTS:Object.fromEntries(Object.entries(metadata.effectContract).map(([key,value])=>[key,slash(value)])),
};

const ts=`// Generated by scripts/generate-schema-identifiers.mjs from contracts/schema-identifiers.json.
// Do not edit by hand.

${Object.entries(groups).map(([name,value])=>`export const ${name}=${JSON.stringify(value,null,2)} as const;`).join('\n\n')}
`;

const agent=groups.AGENT_SCHEMAS;
const agentModule=`// Generated by scripts/generate-schema-identifiers.mjs from contracts/schema-identifiers.json.
// Do not edit by hand.

export const ASSIGNMENT_SCHEMA=${JSON.stringify(agent.assignment)};
export const CANDIDATE_SCHEMA=${JSON.stringify(agent.candidate)};
export const AGENT_TASK_PACKET_SCHEMA=${JSON.stringify(agent.task)};
export const AGENT_RESPONSE_SCHEMA=${JSON.stringify(agent.response)};
`;

const c=groups.COMPUTATION_SCHEMAS;
const go=`// Code generated by scripts/generate-schema-identifiers.mjs; DO NOT EDIT.

package executor

const (
\tComputationExecutionSchema = "${c.execution}"
\tProcessSpecSchema = "${c.processSpec}"
\tComputationEvidenceSchema = "${c.attemptEvidence}"
\tExecutorCommandSchema = "${c.executorCommand}"
\tExecutorHelloSchema = "${c.executorHello}"
)
`;

const mode=process.argv.includes('--write')?'write':'check';
const outputs=[[tsPath,ts],[goPath,go],[agentPath,agentModule]];
let stale=false;
for (const [url,content] of outputs) {
  const path=fileURLToPath(url);
  if (mode==='write') {
    writeFileSync(path,content);
    continue;
  }
  if (readFileSync(path,'utf8')!==content) {
    console.error('STALE_GENERATED_SCHEMA_IDENTIFIERS:'+path.slice(root.length));
    stale=true;
  }
}
if (stale) process.exitCode=1;
